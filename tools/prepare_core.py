from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
s=(root/'third_party/pockemul/sc62015.cpp').read_text()
s=re.sub(r'/\*.*?\*/','',s,flags=re.S)
s=re.sub(r'//[^\n]*','',s)
functions={}
for m in re.finditer(r'(?:inline\s+)?(\w+)\s+Csc62015::(\w+)\s*\(([^)]*)\)\s*\{',s):
 pos=m.end(); depth=1
 while depth:
  depth+=(s[pos]=='{')-(s[pos]=='}');pos+=1
 functions[m[2]]=(m[1],m[3],s[m.end():pos-1])
skip={'init','exit','EMS_Load','EMS_Save','Chk_imemAdr','Chk_imemAdr_Read','AddState','step','get_mem','set_mem','Load_Internal','save_internal','Regs_Info','Get_Xin','Set_Xin','Get_Xout','Set_Xout','compute_xout','get_PC'}
selected={k:v for k,v in functions.items() if k not in skip}
h=(root/'third_party/pockemul/sc62015.h').read_text()
h=h[h.index('#define\t\tMAX_MEM'):h.index('class Csc62015')]
header='''// Adapted from PockEmul SC62015, Copyright (C) Matsumo 1998,1999.
// GPL-2.0-or-later. See ../../third_party/pockemul/COPYING.
// Generated by tools/prepare_core.py; edit the generator or adapter.
#pragma once
#include <cstdint>
#include <cstdio>
#include <cstring>
using BYTE=uint8_t; using WORD=uint16_t; using UINT32=uint32_t; using UINT8=uint8_t;
'''+h+'''\nclass Machine;
class Csc62015 {
public:
 Machine *pPC;
 SCREG reg{};
 BYTE imem[256]{};
 BYTE pre_1=1,pre_2=1;
 bool halt=false,off=false,fault=false;
 int CallSubLevel=0;
 uint64_t cycles=0,ticks=0,ticks2=0;
 explicit Csc62015(Machine *m):pPC(m) {}
 void AddState(BYTE n);
 void Chk_imemAdr_Read(BYTE d,BYTE len);
 void Chk_imemAdr(BYTE d,BYTE len,UINT32 data=0) {}
 void step();
'''
for k,(ret,args,body) in selected.items(): header+=f' {ret} {k}({args});\n'
header+='};\n'
(root/'src/native/sc62015.h').write_text(header)
macros='''#include "machine.h"
#define UN_DEFINE fault=true;
#define OPR1 0
#define OPR2 1
#define Get_BP imem[0xec]
#define Get_PX imem[0xed]
#define Get_PY imem[0xee]
#define Get_i8d(a) imem[(a)&255]
#define Set_i8d(a,d) imem[(a)&255]=(d)
#define Reset_Pre() pre_1=1;pre_2=1
'''
out=header[:header.index('#pragma once')]+macros
for k,(ret,args,body) in selected.items():
 body=body.replace('imem[adr+1]','imem[(adr+1)&255]').replace('imem[adr+2]','imem[(adr+2)&255]')
 out+=f'\n{ret} Csc62015::{k}({args}) {{{body}}}\n'
(root/'src/native/sc62015.cpp').write_text(out)
print('Extracted',len(selected),'CPU functions')

