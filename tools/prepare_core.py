"""PockEmul の SC62015 CPU から、命令の実装を抜き出して src/native/sc62015.h・.cpp を作る。

third_party/pockemul/sc62015.cpp の Csc62015 のメンバ関数のうち、命令の実行とアドレッシングに
必要なもの（skip に挙げたもの以外）を、コメントを除いてそのまま写す。メモリ・タイマー・周辺機器と
つなぐ部分（AddState・step など）は抜き出さず、src/native/machine.cpp に自前で書いてある。
生成したファイルは直接編集せず、このスクリプトか machine.cpp を直すこと。
"""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
# 元のソースを読み、コメントを取り除く（関数の本体を波かっこの対応で切り出すため）。
s=(root/'third_party/pockemul/sc62015.cpp').read_text()
s=re.sub(r'/\*.*?\*/','',s,flags=re.S)
s=re.sub(r'//[^\n]*','',s)
# Csc62015::名前(引数) { ... } をすべて拾い、名前ごとに（戻り値の型、引数、本体）を持つ。
functions={}
for m in re.finditer(r'(?:inline\s+)?(\w+)\s+Csc62015::(\w+)\s*\(([^)]*)\)\s*\{',s):
 pos=m.end(); depth=1
 while depth:
  depth+=(s[pos]=='{')-(s[pos]=='}');pos+=1
 functions[m[2]]=(m[1],m[3],s[m.end():pos-1])
# 本体（Machine）とつなぐ関数や、使わない入出力は写さない。
skip={'init','exit','EMS_Load','EMS_Save','Chk_imemAdr','Chk_imemAdr_Read','AddState','step','get_mem','set_mem','Load_Internal','save_internal','Regs_Info','Get_Xin','Set_Xin','Get_Xout','Set_Xout','compute_xout','get_PC'}
selected={k:v for k,v in functions.items() if k not in skip}
# ヘッダーからは定数・列挙・レジスタの構造体（MAX_MEM から class の手前まで）を写す。
h=(root/'third_party/pockemul/sc62015.h').read_text()
h=h[h.index('#define\t\tMAX_MEM'):h.index('class Csc62015')]
header='''// Adapted from PockEmul SC62015, Copyright (C) Matsumo 1998,1999.
// GPL-2.0-or-later. See ../../third_party/pockemul/COPYING.
// Generated by tools/prepare_core.py; edit the generator or adapter.
//
// SC62015（PC-E500 シリーズの CPU）のエミュレーション。PockEmul の実装から命令の部分を
// tools/prepare_core.py で抜き出したもの。このファイルは直接編集しないこと。
// メモリ・タイマー・周辺機器とのつなぎ（AddState・step など）は machine.cpp にある。
#pragma once
#include <cstdint>
#include <cstdio>
#include <cstring>
using BYTE=uint8_t; using WORD=uint16_t; using UINT32=uint32_t; using UINT8=uint8_t;
'''+h+'''\nclass Machine;
/// SC62015 CPU。命令を1つずつ実行し、メモリには本体（Machine）を通してアクセスする。
class Csc62015 {
public:
 /// メモリと周辺機器を持つ本体。
 Machine *pPC;
 /// レジスタ（A・IL・BA・I・X・Y・U・S・PC・F など）。
 SCREG reg{};
 /// 内部メモリ（256バイト）。F0h 以降はキー・E ポート・割り込み・システム制御の I/O。
 BYTE imem[256]{};
 /// 次の命令の内部メモリのアドレッシングを変えるプリフィクスの状態（1 は通常）。
 BYTE pre_1=1,pre_2=1;
 /// halt：HALT 命令で割り込み待ち。off：電源 OFF。fault：未定義の命令を実行して停止。
 bool halt=false,off=false,fault=false;
 /// サブルーチン呼び出しの深さ（デバッグ用）。
 int CallSubLevel=0;
 /// 起動からのサイクル数と、メイン・サブタイマーの経過サイクル数。
 uint64_t cycles=0,ticks=0,ticks2=0;
 explicit Csc62015(Machine *m):pPC(m) {}
 /// 命令にかかったサイクル数 n を加え、タイマーと周辺機器を進める（machine.cpp）。
 void AddState(BYTE n);
 /// 内部メモリの d から len バイトを読む前に呼ばれる（キー入力の読み直し、machine.cpp）。
 void Chk_imemAdr_Read(BYTE d,BYTE len);
 void Chk_imemAdr(BYTE d,BYTE len,UINT32 data=0) {}
 /// 1命令を実行する（HALT・電源 OFF 中は時間だけ進める、machine.cpp）。
 void step();
 // 以下は PockEmul から抜き出した関数。Op_00〜Op_ff は各オペコードの命令、
 // Get_*・Set_* は内部メモリ（i）・レジスタ（r）・オペランドの読み書き、
 // Reset はリセット、OpExec はオペコードから命令を選んで実行する。
'''
for k,(ret,args,body) in selected.items(): header+=f' {ret} {k}({args});\n'
header+='};\n'
# Windows でも UTF-8・LF で書く（.gitattributes で LF に固定しているため）。
(root/'src/native/sc62015.h').write_text(header,encoding='utf-8',newline='\n')
# 抜き出した関数が使うマクロを、本体とつながるように定義し直す。
macros='''#include "machine.h"
// 未定義の命令：CPU をエラーで止める。
#define UN_DEFINE fault=true;
#define OPR1 0
#define OPR2 1
// 内部メモリの BP・PX・PY レジスタ（内部メモリのアドレッシングの基準）。
#define Get_BP imem[0xec]
#define Get_PX imem[0xed]
#define Get_PY imem[0xee]
// 内部メモリを直接読み書きする（アドレスは 8 ビットで折り返す）。
#define Get_i8d(a) imem[(a)&255]
#define Set_i8d(a,d) imem[(a)&255]=(d)
// プリフィクスを通常に戻す。
#define Reset_Pre() pre_1=1;pre_2=1
'''
out=header[:header.index('#pragma once')]+macros
for k,(ret,args,body) in selected.items():
 # 内部メモリの添字があふれないよう、8 ビットで折り返す。
 body=body.replace('imem[adr+1]','imem[(adr+1)&255]').replace('imem[adr+2]','imem[(adr+2)&255]')
 out+=f'\n{ret} Csc62015::{k}({args}) {{{body}}}\n'
(root/'src/native/sc62015.cpp').write_text(out,encoding='utf-8',newline='\n')
print('Extracted',len(selected),'CPU functions')
